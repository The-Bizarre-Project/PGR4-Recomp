int LanguageIndex(std::string_view name) {
  for (size_t i = 0; i < kLanguages.size(); ++i) {
    if (kLanguages[i] == name) return int(i);
  }
  return -1;  // English, or a language without translations
}

std::string Translate(std::string_view english, int language) {
  if (language < 0 || language >= int(kLanguages.size())) return std::string(english);
  // " *" marks a start-up option's other choices (pgr4_settings.cpp).
  if (english.ends_with(" *")) {
    return Translate(english.substr(0, english.size() - 2), language) + " *";
  }
  if (Table().contains(english)) return std::string(Word(english, language));
  // "Axis 3", "Button 12": the word, then the number.
  for (const std::string_view prefix : {"Axis ", "Button "}) {
    if (english.starts_with(prefix)) {
      return std::string(Word(prefix.substr(0, prefix.size() - 1), language)) + " " +
             std::string(english.substr(prefix.size()));
    }
  }
  // "200 nits": the number, then the word.
  if (english.ends_with(" nits")) {
    return std::string(english.substr(0, english.size() - 5)) + " " +
           std::string(Word("nits", language));
  }
  return std::string(english);
}

